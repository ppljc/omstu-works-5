ALTER TABLE "Cars"
    ADD COLUMN IF NOT EXISTS "Drivetrain"   character varying(20) NOT NULL DEFAULT 'Front',
    ADD COLUMN IF NOT EXISTS "FuelType"     character varying(20) NOT NULL DEFAULT 'Petrol',
    ADD COLUMN IF NOT EXISTS "EngineVolume" real NULL,
    ADD COLUMN IF NOT EXISTS "PowerHp"      integer NULL;

-- Работа может стоить 0 ₽ (гарантийный случай)
ALTER TABLE "ServiceRecords" DROP CONSTRAINT IF EXISTS "CK_ServiceRecords_Cost";
ALTER TABLE "ServiceRecords"
    ADD CONSTRAINT "CK_ServiceRecords_Cost" CHECK ("Cost" >= 0);

CREATE TABLE IF NOT EXISTS "CarPhotos" (
    "Id"         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CarId"      integer                NOT NULL REFERENCES "Cars" ("Id") ON DELETE CASCADE,
    "FileName"   character varying(255) NOT NULL,
    "UploadedAt" timestamp with time zone NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_CarPhotos_FileName" ON "CarPhotos" ("FileName");
CREATE INDEX IF NOT EXISTS "IX_CarPhotos_CarId" ON "CarPhotos" ("CarId");
